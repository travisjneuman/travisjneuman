#!/usr/bin/env node
// Showcase sync: one set of facts → GitHub cards data, README table, and
// tjn.portfolio project data.
//
//   node scripts/showcase/sync-showcase.mjs            # write outputs
//   node scripts/showcase/sync-showcase.mjs --check    # report drift, write nothing
//
// Facts come from each project's showcase.json (sibling checkout ../<repo>/,
// else raw.githubusercontent.com for public repos) or showcase/local/<id>.json.
// Presentation comes from showcase/registry.json.
//
// Outputs:
//   showcase/projects.json                         (cards; then run scripts/cards/generate-cards.mjs)
//   README.md regions <!-- showcase:cards:* --> and <!-- showcase:table:* -->
//   ../tjn.portfolio/src/lib/data/showcase.generated.ts   (when the sibling checkout exists)
//
// Privacy guard (always on): every output is scanned for private terms and the
// run fails on a hit. Terms come from SHOWCASE_DENYLIST (path to a newline list,
// default ~/.config/showcase/denylist.txt) and SHOWCASE_DENYLIST_JSON_URLS
// (comma-separated JSON URLs whose name/alias strings are added). Neither lives
// in this public repo. With no denylist configured the run stops unless
// --allow-no-denylist is passed.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const args = new Set(process.argv.slice(2));
const CHECK = args.has("--check");
const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const registry = readJson(join(root, "showcase/registry.json"));

// ---------------------------------------------------------------- facts
async function loadFacts(id, source) {
  if (source.local) return readJson(join(root, source.local));
  const repoName = source.repo.split("/")[1];
  const sibling = resolve(root, "..", repoName, "showcase.json");
  if (existsSync(sibling)) return readJson(sibling);
  const url = `https://raw.githubusercontent.com/${source.repo}/${source.branch}/showcase.json`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${id}: ${url} → HTTP ${res.status}`);
  return res.json();
}

const facts = {};
for (const [id, source] of Object.entries(registry.sources)) {
  const f = await loadFacts(id, source);
  if (f.id !== id) throw new Error(`registry id ${id} != facts id ${f.id}`);
  for (const key of ["name", "status", "summary", "stack", "metrics", "updated"]) {
    if (f[key] === undefined) throw new Error(`${id}: missing ${key}`);
  }
  facts[id] = f;
}

// ---------------------------------------------------------------- cards
const metricText = (m) => `${m.value} ${m.label.toLowerCase()}`;
const cards = registry.cards.map((c) => {
  const f = facts[c.facts];
  const metrics = (c.metrics ?? [0, 1, 2].map((index) => ({ facts: c.facts, index }))).map((ref) => {
    const m = facts[ref.facts].metrics[ref.index];
    if (!m) throw new Error(`${c.id}: no metric ${ref.facts}[${ref.index}]`);
    return [m.value, ref.label ?? m.label];
  });
  // Alt templates: {mN} → "value label", {vN} → "value"
  const alt = c.alt
    .replace(/\{m(\d)\}/g, (_, i) => {
      const [value, label] = metrics[Number(i)];
      return `${value} ${label.toLowerCase()}`;
    })
    .replace(/\{v(\d)\}/g, (_, i) => metrics[Number(i)][0]);
  const card = {
    id: c.id,
    title: c.title,
    category: c.category,
    status: f.status,
    accent: c.accent,
    lines: c.lines,
    metrics,
    tags: c.tags ?? f.stack.slice(0, 4),
    url: c.url,
    alt,
    anchor: c.anchor,
  };
  if (c.shotFocus) card.shotFocus = c.shotFocus;
  return card;
});
const latest = Object.values(facts).map((f) => f.updated).sort().at(-1);
const projectsJson =
  JSON.stringify(
    {
      $comment:
        "GENERATED by scripts/showcase/sync-showcase.mjs from showcase/registry.json + project showcase.json files. Do not edit; edit the sources and re-run the sync, then scripts/cards/generate-cards.mjs.",
      updated: latest,
      cards,
    },
    null,
    2,
  ) + "\n";

// ---------------------------------------------------------------- README
const STATUS_BADGE = {
  live: "🌐 Live",
  active: "🟢 Active",
  development: "🧪 In development",
  paused: "⏸️ Paused",
  maintained: "🕰️ Maintained",
  retired: "🗄️ Retired",
};
const statusCell = (f) =>
  STATUS_BADGE[f.status] + (f.statusNote ? ` (${f.statusNote})` : "");

const cardsBlock = [
  "<!-- showcase:cards:start (generated by scripts/showcase/sync-showcase.mjs) -->",
  "<table>",
  ...cards.reduce((rows, c, i) => {
    if (i % 2 === 0) rows.push("  <tr>");
    rows.push(
      "    <td width=\"50%\">",
      `      <a href="${c.anchor}"><picture>`,
      `        <source media="(prefers-color-scheme: dark)" srcset="./assets/cards/${c.id}-dark.svg">`,
      `        <img src="./assets/cards/${c.id}-light.svg" alt="${c.alt}" width="100%">`,
      "      </picture></a>",
      "    </td>",
    );
    if (i % 2 === 1 || i === cards.length - 1) rows.push("  </tr>");
    return rows;
  }, []),
  "</table>",
  "<!-- showcase:cards:end -->",
].join("\n");

const tableBlock = [
  "<!-- showcase:table:start (generated by scripts/showcase/sync-showcase.mjs) -->",
  "| Project | Status | What it shows | Links |",
  "|---------|--------|---------------|-------|",
  ...registry.table.map(
    (row) => `| ${row.project} | ${statusCell(facts[row.facts[0]])} · ${row.badges} | ${row.what} | ${row.links} |`,
  ),
  "<!-- showcase:table:end -->",
].join("\n");

function replaceRegion(text, name, block) {
  const re = new RegExp(`<!-- showcase:${name}:start[^>]*-->[\\s\\S]*?<!-- showcase:${name}:end -->`);
  if (!re.test(text)) throw new Error(`README.md is missing the showcase:${name} markers`);
  return text.replace(re, block);
}
const readmePath = join(root, "README.md");
const readmeOld = readFileSync(readmePath, "utf8");
const readmeNew = replaceRegion(replaceRegion(readmeOld, "cards", cardsBlock), "table", tableBlock);

// ---------------------------------------------------------------- portfolio
const portfolioPath = resolve(root, "..", "tjn.portfolio", "src/lib/data/showcase.generated.ts");
const portfolioFacts = Object.fromEntries(
  Object.values(facts)
    .filter((f) => registry.sources[f.id].portfolio !== false)
    .map((f) => [
    f.id,
    {
      status: f.status,
      statusNote: f.statusNote ?? null,
      metrics: f.metrics.slice(0, 3).map((m) => ({ label: m.label, value: m.value })),
    },
  ]),
);
const portfolioJson = `/**
 * GENERATED by travisjneuman/scripts/showcase/sync-showcase.mjs (${latest}).
 * Do not edit: change the project's showcase.json and re-run the sync.
 * projects.ts overlays status, statusNote, and metrics from here.
 */

import type { ProjectStatus } from "./projects";

export interface ShowcaseFacts {
  status: ProjectStatus;
  statusNote: string | null;
  metrics: { label: string; value: string }[];
}

export const showcaseFacts: Record<string, ShowcaseFacts> = ${JSON.stringify(portfolioFacts, null, 2)};
`;

// ---------------------------------------------------------------- privacy guard
async function loadDenylist() {
  const terms = new Set();
  const file = process.env.SHOWCASE_DENYLIST ?? join(homedir(), ".config/showcase/denylist.txt");
  if (existsSync(file)) {
    for (const line of readFileSync(file, "utf8").split("\n")) {
      const t = line.trim();
      if (t && !t.startsWith("#")) terms.add(t);
    }
  }
  for (const url of (process.env.SHOWCASE_DENYLIST_JSON_URLS ?? "").split(",").map((s) => s.trim()).filter(Boolean)) {
    const res = await fetch(url, { headers: { "user-agent": "Mozilla/5.0" } });
    if (!res.ok) throw new Error(`denylist source failed: HTTP ${res.status}`);
    const walk = (v, key = "") => {
      if (typeof v === "string") {
        if (/name|alias/i.test(key)) terms.add(v.replace(/[^\p{L}\p{N}&.'\- ]/gu, "").trim());
      } else if (Array.isArray(v)) v.forEach((x) => walk(x, key));
      else if (v && typeof v === "object") Object.entries(v).forEach(([k, x]) => walk(x, k));
    };
    walk(await res.json());
  }
  // The owner's own public identity is never a leak (league data lists the
  // owner as a member).
  const allow = new Set(["travis", "neuman", "travis neuman", "travis j. neuman", "travisjneuman"]);
  return [...terms].filter((t) => t.length >= 3 && !allow.has(t.toLowerCase()));
}
const deny = await loadDenylist();
if (deny.length === 0 && !args.has("--allow-no-denylist")) {
  console.error("No denylist configured (SHOWCASE_DENYLIST / SHOWCASE_DENYLIST_JSON_URLS). Refusing to run; pass --allow-no-denylist only if you are sure.");
  process.exit(2);
}
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const outputs = { "showcase/projects.json": projectsJson, "README.md": readmeNew, "showcase.generated.ts": portfolioJson };
let leaks = 0;
for (const [name, text] of Object.entries(outputs)) {
  for (const term of deny) {
    if (new RegExp(`(^|[^\\p{L}\\p{N}])${escapeRe(term)}($|[^\\p{L}\\p{N}])`, "iu").test(text)) {
      leaks++;
      console.error(`privacy guard: a denylisted term appears in ${name} (term #${deny.indexOf(term) + 1})`);
    }
  }
}
if (leaks) process.exit(3);

// ---------------------------------------------------------------- write / check
const targets = [
  [join(root, "showcase/projects.json"), projectsJson],
  [readmePath, readmeNew],
];
if (existsSync(dirname(portfolioPath))) targets.push([portfolioPath, portfolioJson]);
else console.warn("tjn.portfolio sibling checkout not found; skipped showcase.generated.ts");

let drift = 0;
for (const [path, text] of targets) {
  const old = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (old === text) continue;
  drift++;
  if (CHECK) console.log(`out of date: ${path}`);
  else {
    writeFileSync(path, text);
    console.log(`wrote ${path}`);
  }
}
if (CHECK) {
  console.log(drift ? `${drift} file(s) out of date` : "showcase outputs are current");
  process.exit(drift ? 1 : 0);
}
console.log(`synced ${Object.keys(facts).length} projects (${deny.length} denylist terms checked)`);
